/**
 * Содержимое информационных страниц `/info/[slug]`.
 *
 * Раздел с юридическими документами (оферта, политика ПДн, условия возврата,
 * реквизиты) живёт здесь же, поэтому раздел страницы описывает не один абзац, а
 * набор абзацев, необязательный список и замыкающее примечание: юридический
 * текст в один абзац не укладывается.
 */

import { LEGAL_PAGES } from "./legalPages";

export interface InfoSection {
  title: string;
  /** Абзацы раздела. У обычной информационной страницы — один. */
  paragraphs: string[];
  /** Маркированный список после абзацев: перечни, состав данных, реквизиты. */
  items?: string[];
  /** Замыкающий абзац после списка — оговорки и исключения. */
  footnote?: string;
}

export interface InfoPage {
  slug: string;
  title: string;
  summary: string;
  /**
   * Баннер над содержимым страницы. Нужен юридическим документам, условия
   * которых ещё требуют подтверждения и юридической проверки.
   */
  notice?: string;
  document?: { href: string; label: string };
  sections: InfoSection[];
}

